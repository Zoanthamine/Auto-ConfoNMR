import tempfile
from pathlib import Path
import unittest
from sampling import normalize_vmd_xyz
from nmrflow import xyz_read


class VMDMappingChecks(unittest.TestCase):
    def fixture(self,root):
        p=Path(root);gro=p/'model.gro'
        gro.write_text('model\n3\n'+''.join(f'{1:5d}{"MOL":<5s}{name:>5s}{i:5d}{0.:8.3f}{0.:8.3f}{0.:8.3f}\n' for i,name in enumerate(['C1','H1','I1'],1))+'1 1 1\n')
        raw=p/'trajectory.xyz';raw.write_text('3\ngenerated by VMD\nC1 0.000 0.0 0.0\nH1 1.090 0.0 0.0\nI1 0.000 0.0 2.100\n')
        return raw,gro,[['C',0.,0.,0.],['H',1.09,0.,0.],['I',0.,0.,2.1]]

    def test_real_numbered_gro_atom_names_preserve_coordinates(self):
        with tempfile.TemporaryDirectory() as root:
            raw,gro,geom=self.fixture(root);original=raw.read_bytes()
            normalized=normalize_vmd_xyz(raw,geom,gro)
            self.assertEqual(xyz_read(normalized)[0][1],geom)
            self.assertEqual(raw.read_bytes(),original)
            self.assertIn('I 0.000 0.0 2.100',normalized.read_text())

    def test_wrong_index_label_is_rejected(self):
        with tempfile.TemporaryDirectory() as root:
            raw,gro,geom=self.fixture(root);raw.write_text(raw.read_text().replace('I1 0.000','C1 0.000'))
            with self.assertRaisesRegex(ValueError,'mapping'):normalize_vmd_xyz(raw,geom,gro)

    def test_truncated_frame_is_rejected(self):
        with tempfile.TemporaryDirectory() as root:
            raw,gro,geom=self.fixture(root);raw.write_text('\n'.join(raw.read_text().splitlines()[:-1])+'\n')
            with self.assertRaisesRegex(ValueError,'truncated'):normalize_vmd_xyz(raw,geom,gro)


if __name__=='__main__':unittest.main()
